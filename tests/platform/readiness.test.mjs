import test from 'node:test';
import assert from 'node:assert/strict';
import {productionReadiness} from '../../lib/platform/readiness.mjs';

test('production readiness fails closed when human/operational evidence is absent',()=>{
  const result=productionReadiness({});
  assert.equal(result.ready,false);
  for(const key of ['BATIC_RELEASE_SHA','BATIC_STANDARDS_REVIEWED_AT','BATIC_SECURITY_RISK_REVIEWED_AT','BATIC_PIA_REVIEWED_AT','BATIC_PRIVACY_APPROVED_AT','BATIC_RETENTION_POLICY_VERSION','BATIC_RETENTION_POLICY_APPROVED_AT','BATIC_BACKUP_RESTORE_TESTED_AT','BATIC_ACCESSIBILITY_VALIDATED_AT','BATIC_REPOSITORY_GOVERNANCE_APPROVED_AT','BATIC_ASSET_RIGHTS_APPROVED_AT','BATIC_DEPENDENCY_LICENSES_APPROVED_AT','BATIC_PRODUCTION_DEPLOYED_SHA','BATIC_PRODUCTION_DEPLOYMENT_URL','BATIC_PRODUCTION_DOMAIN_VALIDATED_AT','BATIC_ROLLBACK_VALIDATED_AT','BATIC_READINESS_REVIEWER','BATIC_READINESS_EVIDENCE_URL']) assert.ok(result.missing.includes(key));
});

