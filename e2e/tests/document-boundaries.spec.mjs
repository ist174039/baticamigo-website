import {test,expect} from '@playwright/test';
import {createHash} from 'node:crypto';
const password='Synthetic-Only-E2E-Password-2026';
async function bearer(request,role='admin'){
 const r=await request.post('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=e2e-only',{data:{email:'qa-'+role+'@example.invalid',password,returnSecureToken:true}});
 expect(r.status()).toBe(200);return (await r.json()).idToken;
}
const h=t=>({Authorization:'Bearer '+t});
const j=t=>({...h(t),'Content-Type':'application/json'});
test('documents: nested folders, inherited read, movement cycles and permission revocation',async ({request})=>{
 const admin=await bearer(request),member=await bearer(request,'member');
 const post=(t,body)=>request.post('/api/platform/document-library',{headers:j(t),data:body});
 const root=await post(admin,{action:'create-folder',name:'Secção E2E',parentId:'',permissions:{viewRoles:['member']}});
 expect(root.status(),await root.text()).toBe(201);const rootId=(await root.json()).id;
 const sub=await post(admin,{action:'create-folder',name:'Subpasta E2E',parentId:rootId});
 expect(sub.status(),await sub.text()).toBe(201);const subId=(await sub.json()).id;
 const list=await request.get('/api/platform/document-library',{headers:h(member)});
 expect(list.status()).toBe(200);
 const visible=(await list.json()).folders.map(x=>x.id);
 expect(visible).toContain(rootId);
 expect(visible).toContain(subId);
 const cycle=await post(admin,{action:'update-folder',folderId:rootId,parentId:subId,name:'Não pode mover'});
 expect(cycle.status()).toBe(400);
 const memberDelete=await post(member,{action:'delete-folder',folderId:subId});
 expect(memberDelete.status()).toBe(403);
 const removeFirst=await post(admin,{action:'delete-folder',folderId:rootId});
 expect(removeFirst.status()).toBe(409);
 const leafDelete=await post(admin,{action:'delete-folder',folderId:subId});
 expect(leafDelete.status()).toBe(200);
 const rootDelete=await post(admin,{action:'delete-folder',folderId:rootId});
 expect(rootDelete.status()).toBe(200);
 const after=await request.get('/api/platform/document-library',{headers:h(member)});
 expect((await after.json()).folders.map(x=>x.id)).not.toContain(rootId);
});
test('documents: immutable versions, download integrity, active content, large files and revoked sharing',async ({request})=>{
 const admin=await bearer(request),member=await bearer(request,'member'),student=await bearer(request,'student');
 const post=body=>request.post('/api/platform/document-library',{headers:j(admin),data:body});
 const pdf=Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\n%%EOF');
 const upload=async t=>request.post('/api/platform/document-library',{headers:h(admin),multipart:{...t,file:t.file||{name:'e2e.pdf',mimeType:'application/pdf',buffer:pdf}}});
 const invalid=await upload({title:'Inválido',category:'institucional',file:{name:'test.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg></svg>')}});
 expect([400,413,415]).toContain(invalid.status());
 const huge=await upload({title:'Demasiado grande',category:'institucional',file:{name:'big.pdf',mimeType:'application/pdf',buffer:Buffer.concat([pdf,Buffer.alloc(4_100_000)])}});
 expect(huge.status()).toBe(413);
 const created=await upload({title:'Registo partilhável',description:'Versões do ficheiro',category:'institucional',permissions:JSON.stringify({viewRoles:['member']})});
 expect(created.status(),await created.text()).toBe(201);
 const item=await created.json();
 const v1=await request.get('/api/platform/document-library?documentId='+item.documentId+'&versionId='+item.versionId,{headers:h(member)});
 expect(v1.status()).toBe(200);
 expect(createHash('sha256').update(Buffer.from(await v1.body())).digest('hex')).toBe(createHash('sha256').update(pdf).digest('hex'));
 const studentDenied=await request.get('/api/platform/document-library?documentId='+item.documentId+'&versionId='+item.versionId,{headers:h(student)});
 expect(studentDenied.status()).toBe(403);
 const updated=await upload({documentId:item.documentId});
 expect(updated.status(),await updated.text()).toBe(201);
 const detail=await request.get('/api/platform/document-library?documentId='+item.documentId,{headers:h(admin)});
 const {document,versions}=await detail.json();
 expect(versions.map(x=>x.number)).toEqual([2,1]);
 expect(versions[1].sha256).toBe(createHash('sha256').update(pdf).digest('hex'));
 const revoke=await post({action:'update-document',documentId:item.documentId,revision:document.revision,permissions:{viewRoles:[]}});
 expect(revoke.status(),await revoke.text()).toBe(200);
 const deniedAfter=await request.get('/api/platform/document-library?documentId='+item.documentId+'&versionId='+item.versionId,{headers:h(member)});
 expect(deniedAfter.status()).toBe(403);
 const invalidVersion=await request.get('/api/platform/document-library?documentId='+item.documentId+'&versionId=../../etc/passwd',{headers:h(admin)});
 expect(invalidVersion.status()).toBe(400);
});
